// CCS/1 (from FolderPilot 0.2.0, via Clickloom 0.3.1) Builds THIRD_PARTY_LICENSES.txt (npm run notices), shipped in the installer next to THIRD_PARTY.md.
// IN:cargo tree -e normal (Windows x64) + cargo metadata -> each crate's own LICENSE*/COPYING*/NOTICE* files;
//    @tauri-apps/api from node_modules; Fluent icons, NSIS, nsis_tauri_utils from licenses/ (copied from upstream)
// OUT:identical texts once, each with the crates that ship it; crates without a licence file listed with SPDX + authors
// --check: exit 1 when the file on disk is out of date
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const manifest = join(root, "src-tauri", "Cargo.toml");
const target = "x86_64-pc-windows-msvc";
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const shipped = new Set(
  run("cargo", ["tree", "--manifest-path", manifest, "-e", "normal", "--target", target, "--prefix", "none", "-f", "{p}"])
    .split(/\r?\n/)
    .map((line) => line.replace(/ \(.*$/, "").trim())
    .filter(Boolean),
);
const meta = JSON.parse(run("cargo", ["metadata", "--manifest-path", manifest, "--format-version", "1", "--filter-platform", target]));
const LICENCE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense)/i;
const norm = (text) => text.replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, "").trim() + "\n";

/** text hash -> { text, users: Set<string> } */
const texts = new Map();
const add = (user, text) => {
  const body = norm(text);
  const key = createHash("sha256").update(body).digest("hex");
  if (!texts.has(key)) texts.set(key, { text: body, users: new Set() });
  texts.get(key).users.add(user);
};

const missing = [];
for (const pkg of meta.packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  const id = `${pkg.name} v${pkg.version}`;
  if (!shipped.has(id) || pkg.name === "panekeeper") continue;
  const dir = dirname(pkg.manifest_path);
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f) && statSync(join(dir, f)).isFile());
  for (const f of files) add(`${pkg.name} ${pkg.version} (${f})`, readFileSync(join(dir, f), "utf8"));
  if (!files.length) missing.push(`${pkg.name} ${pkg.version}: ${pkg.license ?? "no licence field"}; authors: ${(pkg.authors ?? []).join(", ") || "not listed"}`);
}

const local = (user, ...path) => add(user, readFileSync(join(root, ...path), "utf8"));
const npmVersion = (name) => JSON.parse(readFileSync(join(root, "node_modules", "@tauri-apps", name, "package.json"), "utf8")).version;
const api = join("node_modules", "@tauri-apps", "api");
for (const f of readdirSync(join(root, api)).filter((f) => /^LICENSE-/.test(f))) {
  local(`@tauri-apps/api ${npmVersion("api")} (${f})`, api, f);
}
local("Fluent UI System Icons 1.1.345 (SVG paths in the app)", "licenses", "fluentui-system-icons-LICENSE.txt");
local("NSIS 3.13 (installer)", "licenses", "nsis-COPYING.txt");
// Crates whose package has no licence file: their repository's licence (copyright line included).
local("webview2-com, webview2-com-macros, webview2-com-sys (repository LICENSE)", "licenses", "webview2-rs-LICENSE.txt");
local("alloc-stdlib (repository LICENSE)", "licenses", "rust-alloc-no-stdlib-LICENSE.txt");
local("nsis_tauri_utils (installer plug-in, LICENSE_MIT)", "licenses", "nsis-tauri-utils-LICENSE-MIT.txt");
local("nsis_tauri_utils (installer plug-in, LICENSE_APACHE-2.0)", "licenses", "nsis-tauri-utils-LICENSE-APACHE-2.0.txt");

const rule = "=".repeat(78);
let out = `PaneKeeper third-party licences

PaneKeeper itself is MIT licensed (LICENSE.txt). It ships the components below; THIRD_PARTY.md
lists them by name, version and SPDX identifier. This file carries their own licence, copyright
and notice texts, each text once, preceded by the components that ship it.
Generated by scripts/third-party-notices.mjs from the Windows x64 dependency graph.
`;
const groups = [...texts.values()].sort((a, b) => [...a.users][0].localeCompare([...b.users][0]));
for (const { text, users } of groups) out += `\n${rule}\n${[...users].sort().join("\n")}\n${rule}\n\n${text}`;
if (missing.length) {
  out += `\n${rule}\nCrates without a licence file in their package. Their Cargo.toml licence applies; the\nrepository licence is included above where one exists, and the MPL-2.0 text above covers selectors.\n${rule}\n\n${missing.join("\n")}\n`;
}

const file = join(root, "THIRD_PARTY_LICENSES.txt");
if (process.argv.includes("--check")) {
  const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== out) { console.error("THIRD_PARTY_LICENSES.txt is out of date: run npm run notices"); process.exit(1); }
  console.log("THIRD_PARTY_LICENSES.txt is up to date");
} else {
  writeFileSync(file, out);
  console.log(`THIRD_PARTY_LICENSES.txt: ${groups.length} texts for ${shipped.size - 1} crates + npm/icons/installer; ${missing.length} crates without a licence file`);
}
